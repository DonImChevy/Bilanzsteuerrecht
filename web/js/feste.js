function mc(id, thema, text, optionen, ...rest) {
  let richtig = [0], erkl = "", opts = {};
  for (const x of rest) {
    if (Array.isArray(x)) richtig = x;
    else if (typeof x === "string") erkl = x;
    else if (x) opts = x;
  }
  return { id, thema, erzeugen: (r) => auswahl(id, thema, text, optionen, richtig, erkl, r, opts) };
}
